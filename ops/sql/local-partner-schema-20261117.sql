CREATE TABLE public.partners (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name varchar(180) NOT NULL,
  active boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE public.partner_memberships (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  partner_id integer NOT NULL REFERENCES public.partners(id),
  user_id integer NOT NULL REFERENCES public.users_v2(id),
  role varchar(30) NOT NULL,
  active boolean NOT NULL DEFAULT true,
  CONSTRAINT uq_partner_membership UNIQUE (partner_id,user_id)
);
CREATE INDEX ix_partner_memberships_partner_id ON public.partner_memberships (partner_id);
CREATE INDEX ix_partner_memberships_user_id ON public.partner_memberships (user_id);

ALTER TABLE public.companies_v2
